/**
 * Client-Side Governed Export Utilities for IBMFILE Enterprise (ibmfile.com)
 */

export function exportToCsv(data, filename = "ibmfile_export.csv") {
  if (!data || data.length === 0) return;
  const headers = Object.keys(data[0]);
  const csvRows = [];
  
  // Header row
  csvRows.push(headers.map(h => `"${h.replace(/"/g, '""')}"`).join(","));
  
  // Data rows
  for (const row of data) {
    const values = headers.map(header => {
      const val = row[header] ?? "";
      return `"${String(val).replace(/"/g, '""')}"`;
    });
    csvRows.push(values.join(","));
  }
  
  const blob = new Blob(["\uFEFF" + csvRows.join("\r\n")], { type: "text/csv;charset=utf-8;" });
  downloadBlob(blob, filename);
}

export function exportToJson(data, filename = "ibmfile_export.json") {
  if (!data || data.length === 0) return;
  const jsonStr = JSON.stringify(data, null, 2);
  const blob = new Blob([jsonStr], { type: "application/json;charset=utf-8;" });
  downloadBlob(blob, filename);
}

export function exportToExcel(data, filename = "ibmfile_export.xls", title = "IBMFILE Governed Extract") {
  if (!data || data.length === 0) return;
  const headers = Object.keys(data[0]);
  
  let html = `
    <html xmlns:o="urn:schemas-microsoft-com:office:office" xmlns:x="urn:schemas-microsoft-com:office:excel" xmlns="http://www.w3.org/TR/REC-html40">
    <head>
      <meta charset="utf-8" />
      <!--[if gte mso 9]>
      <xml>
        <x:ExcelWorkbook>
          <x:ExcelWorksheets>
            <x:ExcelWorksheet>
              <x:Name>${title}</x:Name>
              <x:WorksheetOptions><x:DisplayGridlines/></x:WorksheetOptions>
            </x:ExcelWorksheet>
          </x:ExcelWorksheets>
        </x:ExcelWorkbook>
      </xml>
      <![endif]-->
      <style>
        table { border-collapse: collapse; font-family: 'IBM Plex Sans', Calibri, sans-serif; }
        th { background-color: #0f62fe; color: #ffffff; font-weight: bold; padding: 10px 14px; border: 1px solid #0043ce; text-align: left; }
        td { padding: 8px 12px; border: 1px solid #e0e0e0; font-size: 13px; }
        tr:nth-child(even) { background-color: #f4f4f4; }
      </style>
    </head>
    <body>
      <h2>${title}</h2>
      <p style="font-size:11px;color:#525252;">Generated by IBMFILE Modernized Studio &bull; ibmfile.com &bull; Date: ${new Date().toISOString()} &bull; Read-Only Governed Extraction</p>
      <table>
        <thead>
          <tr>${headers.map(h => `<th>${h}</th>`).join("")}</tr>
        </thead>
        <tbody>
          ${data.map(row => `<tr>${headers.map(h => `<td>${row[h] ?? ""}</td>`).join("")}</tr>`).join("")}
        </tbody>
      </table>
    </body>
    </html>
  `;
  
  const blob = new Blob([html], { type: "application/vnd.ms-excel;charset=utf-8;" });
  downloadBlob(blob, filename.endsWith(".xls") ? filename : `${filename}.xls`);
}

function downloadBlob(blob, filename) {
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.setAttribute("href", url);
  link.setAttribute("download", filename);
  link.style.visibility = "hidden";
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
